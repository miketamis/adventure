// Pure serializer shared by the sync command and its production release gate.
// Grouping changes only interleaving across nodes, never order within a node:
// source reconciliation searches within that node and retains its tie order.
export function reviewedReadingPartitionSource(name, entries) {
  if (!/^[A-Z_]+$/.test(name)) throw new Error('Invalid reviewed-reading export name')
  const groups = new Map()
  const addresses = new Set()
  const counts = new Map()
  for (const [address, review] of entries) {
    const match = /^([a-zA-Z][a-zA-Z0-9_-]*)\.text\[(0|[1-9]\d*)]$/.exec(address)
    if (!match || !Number.isSafeInteger(Number(match[2])) || addresses.has(address) ||
        typeof review?.al !== 'string' || !review.al.trim() || typeof review?.en !== 'string' || !review.en.trim()) {
      throw new Error(`Invalid or duplicate reviewed-reading address: ${address}`)
    }
    addresses.add(address)
    const [, nodeId, index] = match
    if (!groups.has(nodeId)) groups.set(nodeId, [])
    const pair = `[${JSON.stringify(review.al)}, ${JSON.stringify(review.en)}]`
    groups.get(nodeId).push([index, pair])
    counts.set(pair, (counts.get(pair) || 0) + 1)
  }
  const factories = new Map()
  // Stable pair ordering makes regeneration idempotent after node grouping.
  for (const [pair, count] of [...counts].sort(([left], [right]) => left < right ? -1 : left > right ? 1 : 0)) {
    if (count < 3) continue
    const factory = `repeatedReading${factories.size}`
    const call = `${factory}()`
    const declaration = `const ${factory} = () => ${pair}\n`
    const savedBytes = count * (Buffer.byteLength(pair) - Buffer.byteLength(call)) - Buffer.byteLength(declaration)
    if (savedBytes > 0) factories.set(pair, { call, declaration })
  }
  const declarations = [...factories.values()].map(({ declaration }) => declaration).join('')
  const body = [...groups].map(([nodeId, rows]) =>
    `  [${JSON.stringify(nodeId)}, [\n${rows.map(([index, pair]) =>
      `    [${index}, ${factories.get(pair)?.call || pair}],`).join('\n')}\n  ]],`).join('\n')
  return '// Reviewed whole-line English readings grouped by node, with exact text indices.\n' +
    '// Generated by scripts/reviewedreadingsync.mjs from exact Albanian seals\n' +
    '// and already-authored fluent readings; edit prose with R(), then resync.\n' +
    "import { expandReviewedReadingNodes } from './expandReviewedReadingNodes.js'\n\n" +
    (declarations ? `// Repeated exact pairs still allocate a separate array for every address.\n${declarations}\n` : '') +
    `export const ${name} = expandReviewedReadingNodes([\n${body}\n])\n`
}
