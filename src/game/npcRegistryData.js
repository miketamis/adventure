export const NPC_REGISTRY_SOURCE_FILES = Object.freeze(partitions.map(([file]) => file))
export const NPC_REGISTRY = {}
export const NPC_REGISTRY_SOURCES = {}
for (const [file, partition] of partitions) {
  for (const [id, value] of Object.entries(partition)) {
    if (NPC_REGISTRY[id]) throw new Error(`Duplicate public NPC registry id: ${id}`)
    NPC_REGISTRY[id] = value
    NPC_REGISTRY_SOURCES[id] = file
  }
}
